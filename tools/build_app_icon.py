#!/usr/bin/env python3
"""Build the launcher icon from `Design mockups/App icon.pdf`.

    python tools/build_app_icon.py

Writes, under `android/app/src/main/res/`:

    mipmap-{m,h,x,xx,xxx}hdpi/ic_launcher_foreground.png   the mark, full colour
    drawable/ic_launcher_monochrome.xml                    silhouette, themed icons

Both are generated. Edit the PDF, not the output.

**Why the foreground is a PNG.** It was a VectorDrawable first, converted straight from
the PDF's paths. It compiled and it rendered fine in a desktop SVG renderer, but on the
device both the launcher icon and the splash silently fell back to Android's default
robot. The cause is the mark's hand-drawn outline: one path of ~40,000 characters, past
what the platform will inflate. Dropping that path made the icon appear, which is the
proof -- but dropping it also loses the outline, which is most of the mark's character.
A bitmap has no such limit and adaptive icons accept one, so the artwork ships whole.

Needs PyMuPDF and Pillow:  pip install pymupdf pillow
"""
import argparse
import pathlib
import re
import sys
from collections import deque

REPO = pathlib.Path(__file__).resolve().parent.parent
MOCKUP = REPO / "Design mockups" / "App icon.pdf"
RES = REPO / "android" / "app" / "src" / "main" / "res"

# Adaptive icons are 108 dp with only the central 72 dp guaranteed visible, and a round
# mask cuts the corners off even that. The mark is 2.1:1, so fitting its *width* to 62
# leaves its corners 34.3 dp from centre, inside the 36 dp mask radius.
VIEWPORT_DP = 108
MARK_DP = 62

BUCKETS = [("mdpi", 1), ("hdpi", 1.5), ("xhdpi", 2), ("xxhdpi", 3), ("xxxhdpi", 4)]

# The paper square the PDF draws behind the mark. The adaptive icon's background layer
# is that colour, so the foreground has to be cut free of it.
GROUND = (241, 241, 239)
TOLERANCE = 9


def keyed(image):
    """The ground knocked out from the edges inward, so white *inside* the mark stays."""
    image = image.convert("RGBA")
    px = image.load()
    w, h = image.size

    def is_ground(c):
        return all(abs(c[i] - GROUND[i]) < TOLERANCE for i in range(3))

    seen = [[False] * h for _ in range(w)]
    queue = deque()
    for x in range(w):
        queue.append((x, 0))
        queue.append((x, h - 1))
    for y in range(h):
        queue.append((0, y))
        queue.append((w - 1, y))
    while queue:
        x, y = queue.popleft()
        if x < 0 or y < 0 or x >= w or y >= h or seen[x][y]:
            continue
        seen[x][y] = True
        if not is_ground(px[x, y]):
            continue
        px[x, y] = (0, 0, 0, 0)
        queue.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
    return image


def monochrome(page, mark_box):
    """One copy of the letterform, as a small vector.

    Android 13's themed icons tint a single layer flat, so this needs the mark's shape
    and nothing else -- which is a few hundred characters, nowhere near the limit that
    forced the colour artwork to a bitmap.
    """
    svg = page.get_svg_image(text_as_path=True)
    letters = []
    for m in re.finditer(r"<path([^>]*?)/>", svg):
        attrs = m.group(1)
        matrix = re.search(r"matrix\(1,0,0,-1,([-\d.]+),([-\d.]+)\)", attrs)
        fill = re.search(r'fill="(#[0-9a-fA-F]{6})"', attrs)
        if not matrix or not fill or fill.group(1).upper() != "#FFFFFF":
            continue
        letters.append({
            "d": re.search(r'd="([^"]*)"', attrs).group(1),
            "tx": float(matrix.group(1)),
            "ty": float(matrix.group(2)),
        })
    if not letters:
        raise SystemExit("no letterform path found in the mockup")
    path = min(letters, key=lambda p: len(p["d"]))

    x0, y0, x1, y1 = mark_box
    scale = MARK_DP / (x1 - x0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    half = VIEWPORT_DP / 2
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- The mark as one silhouette, for Android 13 themed icons. The system tints\n'
        '     this flat, so the fill colour is only a fallback.\n'
        '     Generated by tools/build_app_icon.py; edit the PDF and re-run. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        '    <group\n'
        '        android:scaleX="{s:.6f}"\n'
        '        android:scaleY="{ns:.6f}"\n'
        '        android:translateX="{tx:.4f}"\n'
        '        android:translateY="{ty:.4f}">\n'
        '        <path\n'
        '            android:fillColor="#000000"\n'
        '            android:pathData="{d}" />\n'
        '    </group>\n'
        '</vector>\n'
    ).format(
        s=scale, ns=-scale,
        tx=scale * (path["tx"] - cx) + half,
        ty=scale * (path["ty"] - cy) + half,
        d=path["d"],
    )


def main() -> int:
    argparse.ArgumentParser(description=__doc__).parse_args()

    try:
        import fitz
        from PIL import Image
    except ImportError:
        print("needs PyMuPDF and Pillow:  pip install pymupdf pillow", file=sys.stderr)
        return 1

    if not MOCKUP.is_file():
        print("missing " + str(MOCKUP), file=sys.stderr)
        return 1

    page = fitz.open(MOCKUP)[0]

    # Render well above the largest bucket, then key and crop; downsampling from here
    # keeps the outline's drawn edge clean at mdpi.
    render_dpi = 600
    pix = page.get_pixmap(dpi=render_dpi)
    tmp = RES / "_icon_render.png"
    pix.save(tmp)
    art = keyed(Image.open(tmp))
    tmp.unlink()

    box = art.getbbox()
    if not box:
        print("the mockup keyed to nothing -- has the ground colour changed?",
              file=sys.stderr)
        return 1
    art = art.crop(box)

    # The mark's bounds back in the PDF's own points, for the monochrome vector.
    per_pt = render_dpi / 72.0
    mark_box = (box[0] / per_pt, box[1] / per_pt, box[2] / per_pt, box[3] / per_pt)

    for bucket, density in BUCKETS:
        side = round(VIEWPORT_DP * density)
        mark_w = round(MARK_DP * density)
        mark_h = max(1, round(mark_w * art.height / art.width))
        canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        canvas.alpha_composite(
            art.resize((mark_w, mark_h), Image.LANCZOS),
            ((side - mark_w) // 2, (side - mark_h) // 2),
        )
        out = RES / ("mipmap-" + bucket)
        out.mkdir(parents=True, exist_ok=True)
        canvas.save(out / "ic_launcher_foreground.png", optimize=True)

    (RES / "drawable" / "ic_launcher_monochrome.xml").write_text(
        monochrome(page, mark_box), encoding="utf8"
    )

    print("mark %.2f:1, %d dp wide in a %d dp viewport" % (
        art.width / art.height, MARK_DP, VIEWPORT_DP))
    print("wrote ic_launcher_foreground.png x%d and ic_launcher_monochrome.xml"
          % len(BUCKETS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
